// Refresh the bundled copy of Selenium's official rules for AI coding assistants.
// Source: https://github.com/SeleniumHQ/selenium/blob/trunk/rust/src/resources/rules.md (Apache-2.0)
// Usage: node scripts/update-selenium-rules.mjs [path/to/local/rules.md commitSha]
import { readFileSync, writeFileSync } from 'node:fs';

const REPO = 'SeleniumHQ/selenium';
const FILE = 'rust/src/resources/rules.md';
const [localFile, localSha] = process.argv.slice(2);

let text, sha;
if (localFile) {
  text = readFileSync(localFile, 'utf8');
  sha = localSha || 'unknown';
} else {
  const commits = await fetch(`https://api.github.com/repos/${REPO}/commits?path=${FILE}&per_page=1`).then(r => r.json());
  sha = commits[0].sha;
  text = await fetch(`https://raw.githubusercontent.com/${REPO}/${sha}/${FILE}`).then(r => r.text());
}

const out = `// GENERATED by scripts/update-selenium-rules.mjs — do not edit by hand.
//
// Selenium's official rules for AI coding assistants, copied unchanged from
// https://github.com/${REPO}/blob/${sha}/${FILE}
// Copyright Software Freedom Conservancy (SFC), licensed under the Apache License 2.0:
// https://www.apache.org/licenses/LICENSE-2.0

export const SELENIUM_RULES_SOURCE = {
  repository: 'https://github.com/${REPO}',
  path: '${FILE}',
  commit: '${sha}',
  url: 'https://github.com/${REPO}/blob/${sha}/${FILE}',
  license: 'Apache-2.0',
} as const;

export const SELENIUM_RULES_MARKDOWN = ${JSON.stringify(text)};
`;
writeFileSync(new URL('../src/tools/agents/selenium-rules.data.ts', import.meta.url), out);
console.log(`selenium-rules.data.ts updated from ${REPO}@${sha.slice(0, 7)}`);
