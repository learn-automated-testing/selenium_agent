import pytest
from selenium import webdriver
from selenium.webdriver.common.by import By
from selenium.webdriver.support import expected_conditions as EC
from selenium.webdriver.support.ui import Select, WebDriverWait

BASE_URL = "https://practiceautomatedtesting.com/shopping"
BILLING = {
    "billing-firstname": "Test",
    "billing-lastname": "Demo",
    "billing-email": "test.demo@example.com",
    "billing-phone": "+31 20 000 0000",
    "billing-address": "Teststraat 1",
    "billing-city": "Amsterdam",
    "billing-zipcode": "1011 AB",
}


def tid(value: str) -> tuple[str, str]:
    return By.CSS_SELECTOR, f'[data-testid="{value}"]'


@pytest.fixture
def driver():
    driver = webdriver.Chrome()
    driver.set_window_size(1400, 1000)
    yield driver
    driver.quit()


def search(driver, wait, text: str) -> None:
    box = wait.until(EC.visibility_of_element_located(tid("search-input")))
    box.clear()
    box.send_keys(text)


def results_heading(driver) -> str:
    return driver.find_element(By.XPATH, "//h2[starts-with(normalize-space(), 'Search Results')]").text


def test_search_filter_and_buy_with_ideal(driver):
    wait = WebDriverWait(driver, 10)
    driver.get(BASE_URL)

    # 1. Live search
    search(driver, wait, "chair")
    wait.until(lambda d: "(1 products)" in results_heading(d))
    assert driver.find_element(*tid("product-10")).find_element(By.TAG_NAME, "h3").text == "Ergonomic Chair"

    # 2. Filters and sorting: Electronics, in stock only, by price
    search(driver, wait, "")
    Select(driver.find_element(*tid("category-filter"))).select_by_visible_text("Electronics")
    driver.find_element(*tid("in-stock-toggle")).click()
    driver.find_element(*tid("sort-by-price")).click()
    wait.until(lambda d: "(4 products)" in results_heading(d))
    assert not driver.find_elements(*tid("product-3")), "HD Monitor is out of stock and must be filtered out"

    # 3. Add the Mechanical Keyboard
    driver.find_element(*tid("add-to-cart-2")).click()
    cart = driver.find_element(*tid("cart-button"))
    wait.until(lambda d: "1 items" in cart.text and "$89.99" in cart.text)

    # 4 + 5. Product details of the chair on sale, add from the details
    driver.find_element(*tid("clear-filters")).click()
    search(driver, wait, "chair")
    driver.find_element(*tid("product-10")).find_element(By.TAG_NAME, "h3").click()
    details = wait.until(EC.visibility_of_element_located(tid("product-detail-modal")))
    assert "$199.99" in details.text and "$249.99" in details.text and "Save $50.00!" in details.text
    driver.find_element(*tid("add-to-cart-detail")).click()
    driver.find_element(*tid("close-product-detail")).click()
    wait.until(lambda d: "2 items" in cart.text and "$289.98" in cart.text)

    # 6. Checkout: subtotal, free shipping, 21% VAT, total
    driver.execute_script("window.scrollTo(0, 0)")
    wait.until(EC.element_to_be_clickable(tid("cart-button"))).click()
    wait.until(EC.visibility_of_element_located(tid("place-order")))
    checkout = driver.find_element(By.TAG_NAME, "body").text
    for amount in ("Subtotal:", "$289.98", "FREE", "Tax (21%):", "$60.90", "Total:", "$350.88"):
        assert amount in checkout, f"{amount} missing in the order summary"

    # 7. Billing details and iDeal
    for field, value in BILLING.items():
        driver.find_element(*tid(field)).send_keys(value)
    Select(driver.find_element(*tid("billing-country"))).select_by_visible_text("Netherlands")
    driver.find_element(*tid("payment-ideal")).click()
    assert not driver.find_elements(*tid("card-number")), "iDeal must not ask for card details"
    Select(driver.find_element(*tid("ideal-bank"))).select_by_visible_text("ING")

    # 8. Place the order
    driver.find_element(*tid("place-order")).click()
    success = wait.until(EC.visibility_of_element_located(tid("payment-success")))
    assert "Payment Successful" in success.text
